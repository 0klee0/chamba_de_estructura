export function formatIEEEReference(ref: Reference): string {
  const editionStr = ref.edition ? `, ${ref.edition}` : "";
  const pagesStr = ref.pages ? `, ${ref.pages}` : "";
  return `[${ref.id}] ${ref.authors}, "${ref.title}"${editionStr}. ${ref.publication}, ${ref.year}${pagesStr}.`;
}

export function formatBibTeX(ref: Reference): string {
  const key = `${ref.authors.split(' ')[0].toLowerCase()}${ref.year}`;
  return `@book{${key},
  author    = {${ref.authors}},
  title     = {${ref.title}},
  edition   = {${ref.edition || '1st ed.'}},
  publisher = {${ref.publication}},
  year      = {${ref.year}}${ref.pages ? `,\n  pages     = {${ref.pages}}` : ''}
}`;
}
